import React, { useState } from 'react';
import { Terminal, Play, Copy, Check, Sparkles } from 'lucide-react';
import { ScanReport } from '../types/yachiru';

interface CliSimulatorProps {
  report: ScanReport;
  onScanTarget: (noAi: boolean) => void;
}

export const CliSimulator: React.FC<CliSimulatorProps> = ({ report, onScanTarget }) => {
  const [command, setCommand] = useState('yachiru scan --database ' + report.target.database);
  const [outputFormat, setOutputFormat] = useState<'text' | 'json' | 'sql'>('text');
  const [copied, setCopied] = useState(false);

  const generateCliTextReport = () => {
    return `
========================================================================================
 YACHIRU :: CLICKHOUSE 9-DIMENSION OPTIMIZATION SCANNER (v1.0.0)
 Target Database: ${report.target.database} | Cluster: ${report.target.clusterName || report.target.host}
 Scan Timestamp : ${report.timestamp} | Duration: ${report.scanDurationMs}ms
========================================================================================

[+] HEALTH SCORE: ${report.overallScore}/100 [GRADE: ${report.overallGrade}]
[+] TOTAL TABLES: ${report.clusterMetadata.totalTables} | PARTS: ${report.clusterMetadata.totalParts} | COMPRESSED: ${report.clusterMetadata.totalDiskSizeFormatted}
[+] QUERY_LOG ANALYZED: ${report.clusterMetadata.queriesAnalyzed} queries over lookback window

----------------------------------------------------------------------------------------
EXECUTIVE SUMMARY & TOP RISK:
----------------------------------------------------------------------------------------
${report.executiveSummary.overview}

Top Cluster Risk: ${report.executiveSummary.topRisk}

----------------------------------------------------------------------------------------
FINDINGS & ACTIONABLE RECOMMENDATIONS (${report.findings.length} TOTAL):
----------------------------------------------------------------------------------------
${report.findings
  .map(
    (f, idx) => `
[${f.severity.toUpperCase()}] #${idx + 1}: ${f.title}
  Table     : ${f.tableName || 'N/A'} [Dimension: ${f.dimensionName}]
  Evidence  : ${f.what}
  Why       : ${f.whyTechnical}
  Est Impact: ${f.estimatedImpact.magnitude}
  Action    : ${f.recommendationSummary}
  DDL Fix   :
${f.recommendationSql ? f.recommendationSql.split('\n').map((l) => `    ${l}`).join('\n') : '    (No automated DDL required)'}
`
  )
  .join('\n')}
========================================================================================
Generated by Yachiru ClickHouse Advisor (Read-Only Mode)
`;
  };

  const getOutputContent = () => {
    if (outputFormat === 'json') {
      return JSON.stringify(report, null, 2);
    }
    if (outputFormat === 'sql') {
      return report.migrationScript;
    }
    return generateCliTextReport();
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getOutputContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-4">
      {/* CLI Controls */}
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-slate-800 bg-slate-900/80 p-3.5">
        <div className="flex items-center gap-2 font-mono text-xs text-amber-300">
          <Terminal className="h-4 w-4 text-amber-400" />
          <span className="text-slate-400">$</span>
          <span className="font-bold">{command}</span>
        </div>

        <div className="flex items-center gap-2">
          {/* Format selector */}
          <div className="flex rounded-lg border border-slate-800 bg-slate-950 p-1 text-xs">
            <button
              onClick={() => setOutputFormat('text')}
              className={`px-2.5 py-1 rounded font-medium ${
                outputFormat === 'text' ? 'bg-amber-500 text-slate-950 font-bold' : 'text-slate-400'
              }`}
            >
              ANSI CLI Report
            </button>
            <button
              onClick={() => setOutputFormat('json')}
              className={`px-2.5 py-1 rounded font-medium ${
                outputFormat === 'json' ? 'bg-amber-500 text-slate-950 font-bold' : 'text-slate-400'
              }`}
            >
              Raw findings.json
            </button>
            <button
              onClick={() => setOutputFormat('sql')}
              className={`px-2.5 py-1 rounded font-medium ${
                outputFormat === 'sql' ? 'bg-amber-500 text-slate-950 font-bold' : 'text-slate-400'
              }`}
            >
              migration.sql
            </button>
          </div>

          <button
            onClick={handleCopy}
            className="flex items-center gap-1 rounded-lg border border-slate-700 bg-slate-800 px-3 py-1.5 text-xs text-slate-200 hover:bg-slate-700 transition-colors"
          >
            {copied ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" />
                <span className="text-emerald-400">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5 text-slate-400" />
                <span>Copy Output</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Terminal Display */}
      <div className="rounded-xl border border-slate-800 bg-slate-950 shadow-2xl overflow-hidden font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 px-4 py-2 bg-slate-900/60 text-slate-400">
          <div className="flex items-center gap-2">
            <span className="h-2.5 w-2.5 rounded-full bg-rose-500/80" />
            <span className="h-2.5 w-2.5 rounded-full bg-amber-500/80" />
            <span className="h-2.5 w-2.5 rounded-full bg-emerald-500/80" />
            <span className="ml-2 text-[11px]">yachiru-cli stdout</span>
          </div>
          <span className="text-[10px] text-slate-500">UTF-8 Output</span>
        </div>

        <pre className="p-4 sm:p-5 text-emerald-400/90 leading-relaxed overflow-x-auto max-h-[550px] selection:bg-amber-500/30 selection:text-white">
          <code>{getOutputContent()}</code>
        </pre>
      </div>
    </div>
  );
};
